const dictionaries: Record<Locale, Record<MessageKey, string>> = { tr, en };

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  let text = dictionaries[locale][key] ?? tr[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v));
  return text;
}

export function formatTRY(value: number, locale: Locale): string {
  try {
    return new Intl.NumberFormat(locale === 'tr' ? 'tr-TR' : 'en-US', {
      style: 'currency',
      currency: 'TRY',
      maximumFractionDigits: 0,
    }).format(value);
  } catch {
    return `₺${Math.round(value).toLocaleString()}`;
  }
}

export function formatRangeTRY(min: number, max: number, locale: Locale): string {
  return min === max ? formatTRY(min, locale) : `${formatTRY(min, locale)} – ${formatTRY(max, locale)}`;
}

export function formatDate(iso: string, locale: Locale): string {
  try {
    return new Date(iso).toLocaleDateString(locale === 'tr' ? 'tr-TR' : 'en-GB', {
      day: 'numeric',
      month: 'short',
      year: 'numeric',
    });
  } catch {
    return iso.slice(0, 10);
  }
}
